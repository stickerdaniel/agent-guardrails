"""The total-cost workflow, generated from bench/total-contract.json.

    python3 -I -B tools/gen_total.py --check          (CI: nothing differs)
    python3 -I -B tools/gen_total.py --write          (rewrite the workflow)
    python3 -I -B tools/gen_total.py --fill GIT_DIR   (authoring, before freezing)

--fill records in the contract, from `git archive` of each snapshot in
GIT_DIR, the manifest of every file the runner will deliver, and the
treatment order derived from the seed. --check proves the committed workflow
is exactly the one the contract describes: 28 explicit jobs, two chains of
14 joined by needs, only the first of each gated on the label, each job
declaring its own first-party snapshot and no other. It also proves the
order table matches the seed, each manifest matches its digest, and every
file this checkout executes from the candidate or the adapter is
byte-identical to the candidate snapshot's.
"""

from __future__ import annotations

import argparse
import hashlib
import io
import json
import os
import subprocess
import sys
import tarfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
REPOSITORY = os.path.dirname(os.path.dirname(ROOT))
sys.path.insert(0, os.path.join(ROOT, "bench"))
sys.path.insert(0, HERE)
import baseline  # noqa: E402
import total_plan  # noqa: E402

CHECKOUT = "actions/checkout@3d3c42e5aac5ba805825da76410c181273ba90b1"
SETUP_PYTHON = "actions/setup-python@5fda3b95a4ea91299a34e894583c3862153e4b97"
# Candidate files the candidate job executes or reads through the launcher.
EXECUTED = ("launch.sh", "action.yml", "bin/linux-x64/agent-guardrails.gz", "bin/linux-arm64/agent-guardrails.gz")

HEADER = """\
name: {name}

# GENERATED by experiments/native-distribution/tools/gen_total.py from
# experiments/native-distribution/bench/total-contract.json; edit those and
# run it with --write. EXPERIMENTAL Gate X total-cost measurement for the
# unmerged spike pull request only, not a required check.
#
# It runs once, when the label the two first jobs test for is added. Per
# architecture one chain of 14 jobs: seven candidate/control pairs, each
# pair's first treatment fixed in the contract before any job ran, each job
# needing the one before.
# Each job declares exactly one first-party snapshot, in a step that never
# runs, so the runner downloads only that one during Set up job. The worker
# then finds that delivered copy outside the workspace, proves it file by
# file against the contract, and checks the typical capture with it:
#   candidate: the delivered launcher and gzip asset of the native spike,
#   control:   the captured driver on the delivered frozen Python package.
# bench/total_analyze.py times every job from the runner's "Getting action
# download info" line to the worker's end marker, from downloaded logs.
# Read-only token, no secrets, nothing published.
on:
  pull_request:
    types: [labeled]

permissions:
  contents: read

concurrency:
  group: native-distribution-total-${{{{ github.event.pull_request.number }}}}
  cancel-in-progress: false

jobs:
"""

JOB = """\
  {id}:
    name: {name}
{gate}    runs-on: {runner}
    timeout-minutes: {timeout}
    steps:
      - uses: {checkout} # {checkout_version}
        with:
          ref: ${{{{ github.event.pull_request.head.sha }}}}
          persist-credentials: false
      - id: python
        uses: {setup_python} # {setup_python_version}
        with:
          python-version: "{python}"
      - name: Generate the typical capture
        env:
          PY314: ${{{{ steps.python.outputs.python-path }}}}
        run: |
          "$PY314" -I -B experiments/native-distribution/bench/gen_corpora.py --out "$RUNNER_TEMP/corpora" --case {case}
      - name: Deliver the {treatment} snapshot, never run as a step
        # Attempts start at 1, so this never runs: the step exists to be
        # delivered during Set up job, and the next step runs those bytes.
        if: github.run_attempt == '0'
        uses: {uses} # unmerged experiment
{with_}      - name: Check the typical capture with the delivered snapshot
        env:
          PY314: ${{{{ steps.python.outputs.python-path }}}}
          AGX_SOURCE_SHA: ${{{{ github.event.pull_request.head.sha }}}}
        run: |
          "$PY314" -I -B experiments/native-distribution/bench/total_run.py \\
            --job {id} --capture "$RUNNER_TEMP/corpora/{case}.cap"
"""

# The candidate action requires its capture input; the step never runs, but
# stays a complete declaration of the action.
CANDIDATE_WITH = """\
        with:
          capture: ${{{{ runner.temp }}}}/corpora/{case}.cap
"""


def render(contract: dict) -> str:
    third = contract["third_party"]
    parts = []
    for job in total_plan.jobs(contract):
        if job["needs"] is None:
            gate = f"    if: github.event.label.name == '{contract['label']}'\n"
        else:
            gate = f"    needs: {job['needs']}\n"
        parts.append(JOB.format(
            id=job["id"],
            name=job["name"],
            gate=gate,
            runner=job["runner"],
            timeout=contract["job_timeout_minutes"],
            checkout=CHECKOUT,
            checkout_version=third[CHECKOUT],
            setup_python=SETUP_PYTHON,
            setup_python_version=third[SETUP_PYTHON],
            python=contract["python"]["version"],
            case=contract["case"],
            treatment=job["treatment"],
            uses=contract["treatments"][job["treatment"]]["uses"],
            with_=CANDIDATE_WITH.format(case=contract["case"]) if job["treatment"] == "candidate" else "",
        ))
    return HEADER.format(name=contract["workflow"]["name"]) + "\n".join(parts)


def sha256_file(path: str) -> str:
    with open(path, "rb") as handle:
        return hashlib.sha256(handle.read()).hexdigest()


def archive_manifest(git_dir: str, sha: str) -> dict:
    """{path: sha256} of every file in `git archive sha`, the tree GitHub's
    tarball of that commit holds."""
    data = subprocess.run(
        ["git", "-C", git_dir, "archive", "--format=tar", sha], capture_output=True, check=True
    ).stdout
    manifest = {}
    with tarfile.open(fileobj=io.BytesIO(data)) as archive:
        for member in archive.getmembers():
            if member.isfile():
                manifest[member.name] = hashlib.sha256(archive.extractfile(member).read()).hexdigest()
            elif not member.isdir() and member.type != tarfile.XGLTYPE:
                raise SystemExit(f"gen_total: {sha} has {member.name}, which is not a regular file")
    return dict(sorted(manifest.items()))


def check(contract: dict, workflow_text: str) -> list[str]:
    problems = []
    if contract["first"] != total_plan.first_order(contract["seed"], contract["pairs"]):
        problems.append("the order table is not first_order(seed, pairs)")
    for arch in total_plan.ARCHES:
        if len(contract["first"].get(arch, [])) != contract["pairs"]:
            problems.append(f"{arch} does not have {contract['pairs']} pairs")
    for name, treatment in contract["treatments"].items():
        if not treatment["manifest"] or total_plan.manifest_sha256(treatment["manifest"]) != treatment["manifest_sha256"]:
            problems.append(f"the {name} manifest does not match its digest")
        if not treatment["uses"].endswith("@" + treatment["snapshot"]):
            problems.append(f"the {name} uses reference does not name its snapshot")
    candidate = contract["treatments"]["candidate"]["manifest"]
    for relative in [f"{contract['treatments']['candidate']['action_dir']}/{name}" for name in EXECUTED] + contract["adapter"]:
        here = os.path.join(REPOSITORY, relative)
        if candidate.get(relative) is None:
            problems.append(f"{relative} is not in the candidate snapshot")
        elif not os.path.isfile(here) or sha256_file(here) != candidate[relative]:
            problems.append(f"{relative} in this checkout differs from the candidate snapshot")
    control = contract["treatments"]["control"]["manifest"]
    for name, digest in baseline.PACKAGE_SHA256.items():
        if control.get(f"agent_guardrails/{name}") != digest:
            problems.append(f"the control manifest's agent_guardrails/{name} is not tools/baseline.py's")
    if contract["treatments"]["control"]["snapshot"] != baseline.BASELINE_COMMIT:
        problems.append("the control snapshot is not tools/baseline.py's commit")
    if len(total_plan.jobs(contract)) != 2 * 2 * contract["pairs"]:
        problems.append("the plan does not have two jobs per pair and architecture")
    if workflow_text != render(contract):
        problems.append(f"{contract['workflow']['path']} is not what the contract generates; run --write")
    return problems


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--fill", metavar="GIT_DIR")
    args = parser.parse_args(argv)
    contract, _ = total_plan.load()
    workflow = os.path.join(REPOSITORY, contract["workflow"]["path"])
    if args.fill:
        for treatment in contract["treatments"].values():
            treatment["manifest"] = archive_manifest(args.fill, treatment["snapshot"])
            treatment["manifest_sha256"] = total_plan.manifest_sha256(treatment["manifest"])
        contract["first"] = total_plan.first_order(contract["seed"], contract["pairs"])
        with open(total_plan.CONTRACT, "w", encoding="ascii") as handle:
            json.dump(contract, handle, indent=2)
            handle.write("\n")
        return 0
    if args.write:
        with open(workflow, "w", encoding="ascii") as handle:
            handle.write(render(contract))
        return 0
    with open(workflow, encoding="ascii") as handle:
        problems = check(contract, handle.read())
    for problem in problems:
        print(f"gen_total: {problem}", file=sys.stderr)
    return 1 if problems else 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
